# Build Release plugin + freeze backend + compile Inno Setup installer.
param(
    [string]$Configuration = "Release",
    [string]$RevitInstallPath = "",
    [string]$InnoCompiler = "",
    [switch]$SkipPlugin,
    [switch]$SkipBackend,
    [switch]$SkipInno,
    [switch]$SkipRevitCheck
)

$ErrorActionPreference = "Stop"
$repoRoot = Split-Path -Parent $PSScriptRoot
$versionFile = Join-Path $repoRoot "version.txt"
if (-not (Test-Path $versionFile)) {
    Write-Error "Missing version.txt at repo root."
}
$version = (Get-Content -Raw $versionFile).Trim()
if ($version -notmatch '^\d+\.\d+\.\d+') {
    Write-Error "version.txt must contain a semver like 1.0.0 (got '$version')."
}

Write-Host "Packaging BIM Agentic Bridge $version" -ForegroundColor Cyan

# Sync Inno version define
$versionIss = Join-Path $repoRoot "installer\version.iss"
@"
; Generated by scripts/package-release.ps1 — do not hand-edit for releases.
#define MyAppVersion "$version"
"@ | Set-Content -Path $versionIss -Encoding ASCII

$payload = Join-Path $repoRoot "dist\payload"
$pluginOut = Join-Path $payload "Plugin"
$backendOut = Join-Path $payload "Backend"
New-Item -ItemType Directory -Force -Path $pluginOut | Out-Null

# --- Plugin ---
if (-not $SkipPlugin) {
    $revit = Get-Process -Name "Revit" -ErrorAction SilentlyContinue
    if ($revit) {
        Write-Error "Close Autodesk Revit before packaging (it locks the plugin DLL)."
    }

    $buildArgs = @{
        Configuration = $Configuration
    }
    if ($RevitInstallPath) {
        $buildArgs["RevitInstallPath"] = $RevitInstallPath
    }
    & (Join-Path $PSScriptRoot "build-plugin.ps1") @buildArgs
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

    # build-plugin installs Debug/Release addin for dev — also stage Release bits for installer.
    $builtDir = Join-Path $repoRoot "revit-plugin\BimAgenticBridge\bin\$Configuration"
    $dll = Join-Path $builtDir "BimAgenticBridge.dll"
    if (-not (Test-Path $dll)) {
        Write-Error "Built plugin DLL not found: $dll"
    }

    New-Item -ItemType Directory -Force -Path $pluginOut | Out-Null
    Copy-Item -Force (Join-Path $builtDir "BimAgenticBridge.dll") $pluginOut
    $newtonsoft = Join-Path $builtDir "Newtonsoft.Json.dll"
    if (Test-Path $newtonsoft) {
        Copy-Item -Force $newtonsoft $pluginOut
    } else {
        Write-Warning "Newtonsoft.Json.dll not found next to plugin — ensure it is copied on build."
    }
    Write-Host "Staged plugin → $pluginOut"
}

# --- Backend freeze ---
if (-not $SkipBackend) {
    & (Join-Path $PSScriptRoot "build-backend-exe.ps1")
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
    $exe = Join-Path $backendOut "BimAgenticBridge.Backend.exe"
    $cmd = Join-Path $backendOut "BimAgenticBridge.Backend.cmd"
    if (-not (Test-Path $exe) -and -not (Test-Path $cmd)) {
        Write-Error "Frozen/portable backend missing under $backendOut"
    }
}

# --- Inno Setup ---
if (-not $SkipInno) {
    if (-not $InnoCompiler) {
        $candidates = @(
            "${env:ProgramFiles(x86)}\Inno Setup 6\ISCC.exe",
            "${env:ProgramFiles}\Inno Setup 6\ISCC.exe"
        )
        foreach ($c in $candidates) {
            if (Test-Path $c) { $InnoCompiler = $c; break }
        }
    }
    if (-not $InnoCompiler -or -not (Test-Path $InnoCompiler)) {
        Write-Error "Inno Setup 6 compiler (ISCC.exe) not found. Install from https://jrsoftware.org/isinfo.php"
    }

    if (-not (Test-Path (Join-Path $pluginOut "BimAgenticBridge.dll"))) {
        Write-Error "Payload plugin missing. Run without -SkipPlugin."
    }
    $exe = Join-Path $backendOut "BimAgenticBridge.Backend.exe"
    $cmd = Join-Path $backendOut "BimAgenticBridge.Backend.cmd"
    if (-not (Test-Path $exe) -and -not (Test-Path $cmd)) {
        Write-Error "Payload backend missing. Run without -SkipBackend."
    }

    $iss = Join-Path $repoRoot "installer\BimAgenticBridge.iss"
    Write-Host "Compiling installer with $InnoCompiler"
    & $InnoCompiler $iss
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

    $setup = Join-Path $repoRoot "dist\BIMAgenticBridge-Setup-$version.exe"
    if (-not (Test-Path $setup)) {
        Write-Error "Expected installer not found: $setup"
    }

    Write-Host ""
    Write-Host "Release artifact:" -ForegroundColor Green
    Write-Host "  $setup"
    Write-Host ""
    Write-Host "Next: upload to GitHub Releases. Sign with Authenticode before commercial distribution."
}

Write-Host "Done."
